/**
 * Embeds supabase/migrations/*.sql into src/migrations.gen.ts for the open-gate.
 * Run after `drizzle-kit generate`: `bun packages/store/scripts/gen-migrations.ts`.
 * tests/migrations.test.ts fails when the checked-in file is stale.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { sha256Hex } from "@memindex/model";

export const MIGRATIONS_DIR = join(import.meta.dir, "../../../supabase/migrations");
export const GEN_FILE = join(import.meta.dir, "../src/migrations.gen.ts");

const FILE = /^(\d{14})_(.+)\.sql$/;

export function renderMigrationsModule(dir: string = MIGRATIONS_DIR): string {
  const files = readdirSync(dir)
    .filter((f) => FILE.test(f))
    .sort();
  const entries = files.map((f) => {
    const m = FILE.exec(f);
    if (!m?.[1] || !m[2]) throw new Error(`bad migration file name ${f}`);
    const sql = readFileSync(join(dir, f), "utf8");
    return `  {\n    version: ${JSON.stringify(m[1])},\n    name: ${JSON.stringify(m[2])},\n    sha256: ${JSON.stringify(sha256Hex(sql))},\n    sql: ${JSON.stringify(sql)},\n  },`;
  });
  return `// Generated by scripts/gen-migrations.ts from supabase/migrations. Do not edit.

export interface EmbeddedMigration {
  readonly version: string;
  readonly name: string;
  readonly sha256: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly EmbeddedMigration[] = [
${entries.join("\n")}
];
`;
}

if (import.meta.main) {
  writeFileSync(GEN_FILE, renderMigrationsModule());
  console.log(`wrote ${GEN_FILE}`);
}
